/// Context for generating a UI/UX design variant.
/// Passed to `LLMProvider::generate_design()` by the Visionary specialist.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DesignContext {
    /// What kind of user intent to address (e.g., "dashboard", "onboarding flow")
    pub intent: String,
    /// Style preferences from engrams / previous user feedback
    pub style_hints: Vec<String>,
    /// Constraints (e.g., "mobile-first", "accessibility required", "dark theme")
    pub constraints: Vec<String>,
    /// Number of distinct variants to generate
    pub variants_requested: usize,
    /// Recent approved designs to learn from
    pub approved_examples: Vec<String>,
    /// Recent rejected designs to avoid
    pub rejected_examples: Vec<String>,
}

/// A single UI/UX design variant generated by the LLM.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DesignVariant {
    /// Short title
    pub title: String,
    /// Prose description of the design (layout, colors, typography, interactions)
    pub description: String,
    /// Color palette tokens (hex strings or named tokens)
    pub colors: Vec<String>,
    /// Typography choices
    pub typography: String,
    /// Layout approach (e.g., "single-column", "card grid", "sidebar-nav")
    pub layout: String,
    /// How likely the model thinks this design will be approved (0.0-1.0)
    pub confidence: f32,
    /// Model's reasoning for this choice
    pub reasoning: String,
}

/// The full design generation response from the LLM.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DesignGeneration {
    /// Which intent this generation addresses
    pub intent: String,
    /// The generated variants (length <= `DesignContext::variants_requested`)
    pub variants: Vec<DesignVariant>,
    /// Estimated token cost (0 for local GGUF)
    pub tokens_used: u32,
    /// Overall confidence in the generation batch
    pub batch_confidence: f32,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_task_analysis_context_creation() {
        let context = TaskAnalysisContext {
            task_id: "task1".to_string(),
            file_name: "data.csv".to_string(),
            file_size: 1024,
            file_type: "csv".to_string(),
            data_sample: "id,name,value\n1,A,100".to_string(),
            specialist_skills: vec!["RAG".to_string()],
            specialist_domain: "analysis".to_string(),
            team_context: "Team has 6 specialists".to_string(),
        };

        assert_eq!(context.task_id, "task1");
    }

    #[test]
    fn test_task_analysis_serialization() {
        let analysis = TaskAnalysis {
            task_id: "task1".to_string(),
            analysis_type: "data_analysis".to_string(),
            complexity: Complexity::Moderate,
            recommended_approach: "Use RAG".to_string(),
            estimated_time_minutes: 30,
            confidence_percentage: 85,
            suggested_collaborators: vec!["Circe".to_string()],
            potential_risks: vec!["Data quality".to_string()],
            reasoning: "Good approach".to_string(),
        };

        let json = serde_json::to_string(&analysis).unwrap();
        let deserialized: TaskAnalysis = serde_json::from_str(&json).unwrap();
        assert_eq!(deserialized.task_id, "task1");
    }
}
