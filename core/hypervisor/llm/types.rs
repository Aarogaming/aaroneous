// LLM Integration Types
// Core data structures for reasoning and analysis

use serde::{Deserialize, Serialize};

/// Context for analyzing a task
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskAnalysisContext {
    pub task_id: String,
    pub file_name: String,
    pub file_size: u64,
    pub file_type: String,
    pub data_sample: String,           // First N rows/bytes
    pub specialist_skills: Vec<String>, // Current specialist skills
    pub specialist_domain: String,
    pub team_context: String, // What other specialists are available
}

/// Result of task analysis
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskAnalysis {
    pub task_id: String,
    pub analysis_type: String, // e.g., "sentiment_analysis", "data_cleaning"
    pub complexity: Complexity,
    pub recommended_approach: String,
    pub estimated_time_minutes: u32,
    pub confidence_percentage: u32,
    pub suggested_collaborators: Vec<String>, // Names of specialists to ask
    pub potential_risks: Vec<String>,
    pub reasoning: String, // Why this approach
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub enum Complexity {
    Simple,    // <5 minutes
    Moderate,  // 5-30 minutes
    Complex,   // 30+ minutes
}

/// Context for finding collaborators
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SpecialistContext {
    pub name: String,
    pub archetype: String,
    pub rank: u32,
    pub xp: u32,
    pub skills: Vec<SkillInfo>,
    pub recent_lessons: Vec<String>,
    pub collaboration_history: Vec<String>,
    pub current_goal: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SkillInfo {
    pub name: String,
    pub level: u32,
    pub is_awakened: bool,
}

/// Suggestion for collaboration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CollaboratorSuggestion {
    pub specialist_name: String,
    pub reason: String,
    pub relevance_score: f32, // 0.0-1.0
    pub complementary_skills: Vec<String>,
}

/// Execution plan generated by LLM
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExecutionPlan {
    pub task_id: String,
    pub specialist_name: String,
    pub steps: Vec<PlanStep>,
    pub total_estimated_time: u32,
    pub success_probability: f32,
    pub reasoning: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanStep {
    pub sequence: u32,
    pub description: String,
    pub estimated_time_minutes: u32,
    pub required_skills: Vec<String>,
    pub checkpoints: Vec<String>, // Validation points
}

/// Context for failure analysis
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FailureContext {
    pub task_id: String,
    pub specialist_name: String,
    pub error_message: String,
    pub attempted_approach: String,
    pub available_skills: Vec<String>,
    pub previous_attempts: Vec<String>,
}

/// Analysis of failure with recovery suggestion
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FailureAnalysis {
    pub root_cause: String,
    pub explanation: String,
    pub prevention_strategy: String,
    pub recovery_approach: String,
    pub new_strategy: String,
    pub confidence_percentage: u32,
}

/// Explanation of a skill
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SkillExplanation {
    pub skill_name: String,
    pub description: String,
    pub use_cases: Vec<String>,
    pub example: String,
    pub how_to_improve: String,
    pub synergies_with: Vec<String>, // Other skills it combines well with
}

/// Specialist's reasoning about a decision
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DecisionReasoning {
    pub decision: String,
    pub reasoning: String,
    pub alternatives_considered: Vec<String>,
    pub confidence_level: f32, // 0.0-1.0
    pub reasoning_timestamp: String,
}

/// Goal suggestion for specialist
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GoalSuggestion {
    pub goal_description: String,
    pub rationale: String,
    pub target_skills: Vec<String>,
    pub estimated_timeframe_days: u32,
    pub milestones: Vec<String>,
    pub expected_impact: String,
}

/// Specialist's memory of a lesson
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LessonMemory {
    pub lesson_id: String,
    pub lesson_text: String,
    pub when_learned: String,
    pub context: String,
    pub applicability: f32, // 0.0-1.0
}

/// Specialist's strategy for task type
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Strategy {
    pub strategy_id: String,
    pub task_type: String,
    pub approach: String,
    pub steps: Vec<String>,
    pub success_rate: f32, // Based on past experience
    pub last_used: String,
    pub improvements_noted: Vec<String>,
}

/// LLM Query for reasoning
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LLMQuery {
    pub query_type: QueryType,
    pub content: String,
    pub context: String,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub enum QueryType {
    TaskAnalysis,
    CollaboratorFinding,
    ExecutionPlanning,
    FailureAnalysis,
    SkillExplanation,
    StrategyDecision,
    GoalSetting,
}

/// LLM Response wrapper
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LLMResponse {
    pub response_type: ResponseType,
    pub content: String,
    pub tokens_used: u32,
    pub confidence: f32,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub enum ResponseType {
    Analysis,
    Plan,
    Suggestion,
    Explanation,
    Decision,
}

